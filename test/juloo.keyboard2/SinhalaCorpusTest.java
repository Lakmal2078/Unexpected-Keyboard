  @Test
  public void testCorpusQualityAndCategoryThresholds()
  {
    List<TestCase> corpus = getCorpus();
    assertEquals("Corpus must contain exactly 1,000 test items", 1000, corpus.size());

    Map<String, int[]> stats = new LinkedHashMap<>();
    List<String> failures = new ArrayList<>();

    for (TestCase tc : corpus)
    {
      stats.putIfAbsent(tc.category, new int[]{0, 0});
      stats.get(tc.category)[0]++;

      String actual = SinhalaTransliterator.transliterate(tc.input);
      if (actual.equals(tc.expected))
      {
        stats.get(tc.category)[1]++;
      }
      else
      {
        failures.add("[" + tc.category + "] Input: '" + tc.input + "' -> Expected: '" + tc.expected + "', Got: '" + actual + "'");
      }
    }

    int totalTested = corpus.size();
    int totalPassed = totalTested - failures.size();
    double overallAccuracy = (double) totalPassed / totalTested * 100.0;

    System.out.println("=================================================");
    System.out.println("     SINHALA 1,000-INPUT CORPUS TEST RESULTS     ");
    System.out.println("=================================================");
    for (Map.Entry<String, int[]> e : stats.entrySet())
    {
      int catTot = e.getValue()[0];
      int catPass = e.getValue()[1];
      double pct = (double) catPass / catTot * 100.0;
      System.out.printf("  %-32s: %3d / %3d (%6.2f%%)%n", e.getKey(), catPass, catTot, pct);
    }
    System.out.println("-------------------------------------------------");
    System.out.printf("  TOTAL ACCURACY                  : %3d / %3d (%6.2f%%)%n",
        totalPassed, totalTested, overallAccuracy);
    System.out.println("=================================================");

    if (!failures.isEmpty())
    {
      System.out.println("Failing cases (" + failures.size() + "):");
      for (String f : failures)
      {
        System.out.println("  " + f);
      }
    }

    // Requirement assertions
    assertTrue("Overall accuracy must reach at least 95% (got " + overallAccuracy + "%)",
        overallAccuracy >= 95.0);

    double yansayaAccuracy = (double) stats.get("Yansaya")[1] / stats.get("Yansaya")[0] * 100.0;
    assertTrue("Yansaya accuracy must reach at least 95% (got " + yansayaAccuracy + "%)",
        yansayaAccuracy >= 95.0);

    double rakaransayaAccuracy = (double) stats.get("Rakaransaya")[1] / stats.get("Rakaransaya")[0] * 100.0;
    assertTrue("Rakaransaya accuracy must reach at least 95% (got " + rakaransayaAccuracy + "%)",
        rakaransayaAccuracy >= 95.0);

    double repayaAccuracy = (double) stats.get("Repaya")[1] / stats.get("Repaya")[0] * 100.0;
    assertTrue("Repaya accuracy must reach at least 95% (got " + repayaAccuracy + "%)",
        repayaAccuracy >= 95.0);

    double sanskritAccuracy = (double) stats.get("Sanskrit/Pali Words")[1] / stats.get("Sanskrit/Pali Words")[0] * 100.0;
    assertTrue("Sanskrit/Pali accuracy must reach at least 90% (got " + sanskritAccuracy + "%)",
        sanskritAccuracy >= 90.0);
  }

